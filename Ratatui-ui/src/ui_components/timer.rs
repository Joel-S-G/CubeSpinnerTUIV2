use crate::app::App;
use ratatui::{
    Frame,
    layout::{self, Constraint, Direction, Layout},
    widgets::{Block, Borders, Paragraph},
};

pub fn draw(frame: &mut Frame, app: &App) {
    let layout = Layout::default()
        .direction(Direction::Vertical)
        .constraints([
            Constraint::Length(3),
            Constraint::Min(1),
            Constraint::Length(2),
        ])
        .split(frame.area());
    let title = Paragraph::new("CubeSpinner").block(Block::default().borders(Borders::ALL));

    let timer_text = format_elapsed(app);

    let timer =
        Paragraph::new(timer_text).block(Block::default().title("Timer").borders(Borders::ALL));

    let help = Paragraph::new("(S)tart/Stop   (Q)uit")
        .block(Block::default().title("Hints").borders(Borders::ALL));

    frame.render_widget(title, layout[0]);

    frame.render_widget(timer, layout[1]);

    frame.render_widget(help, layout[2]);
}
